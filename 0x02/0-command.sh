# command line terminal

ls # list files and directories (folder)
ls -l #  list files and directories in long format
touch filename # create a new empty file
mkdir foldername # create a new directory
cd foldername  # change directory to foldername or (copy foldername)
cd .. # move up one directory level (back)
pwd # print working directory  (current directory)
cp source.txt destination.txt # copy a file
mv oldname.txt newname.txt # rename a file
rm filename.txt # remove/delete a filess
cat filename.txt # display the contents of file
rm -r foldername # remove/delete a directory and its contents